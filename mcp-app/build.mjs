#!/usr/bin/env node
// Builds the MCP Apps proposal card (S1 of docs/superpowers/plans/2026-10-21-owt-mcp-proposal-editor.md)
// into ONE self-contained HTML document and writes it to `mcp-app/generated/proposalCardHtml.ts`,
// which `/api/mcp` serves as the `ui://owt/proposal-editor` resource.
//
// One inline document because the host renders it in a sandboxed iframe whose CSP admits no
// other origin: a <script src> or a font URL would simply not load. The output is committed
// (no build step on Vercel, no file to trace into the function) and a vitest guard
// (`app/mcp/apps/__tests__/proposalCard.test.tsx`) rebuilds it and fails when the committed
// bytes are stale — so after changing anything under `mcp-app/proposal-card/`, run:
//
//     node mcp-app/build.mjs

import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const GENERATED_FILE = path.join(HERE, "generated", "proposalCardHtml.ts");

/** The card as one HTML string: the bundle's CSS and JS inlined, nothing fetched. */
export async function buildProposalCardHtml() {
  const result = await build({
    entryPoints: [path.join(HERE, "proposal-card", "main.tsx")],
    bundle: true,
    write: false,
    outdir: "out",
    format: "iife",
    platform: "browser",
    target: ["es2020", "safari15"],
    minify: true,
    legalComments: "none",
    charset: "utf8",
    jsx: "automatic",
    define: { "process.env.NODE_ENV": '"production"' },
    logLevel: "silent",
  });
  const js = result.outputFiles.find((f) => f.path.endsWith(".js"))?.text ?? "";
  const css = result.outputFiles.find((f) => f.path.endsWith(".css"))?.text ?? "";
  if (!js) throw new Error("proposal card: esbuild produced no script");
  if (/<\/style/i.test(css)) throw new Error("proposal card: the stylesheet contains </style");
  // Inside an inline <script>, `</script` ends the element and `<!--` can switch the parser into
  // an escaped state. `<\/script` means the same thing to JS (string, regex or template); a
  // `<!--` is refused outright rather than rewritten.
  const safeJs = js.replace(/<\/script/gi, "<\\/script");
  if (safeJs.includes("<!--")) throw new Error("proposal card: the script contains <!--");
  return [
    "<!doctype html>",
    '<html lang="es">',
    "<head>",
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">',
    "<title>Propuesta del mes</title>",
    `<style>${css}</style>`,
    "</head>",
    "<body>",
    '<div id="root"></div>',
    `<script>${safeJs}</script>`,
    "</body>",
    "</html>",
    "",
  ].join("\n");
}

/** The generated module's exact text for a given document. */
export function generatedModule(html) {
  return [
    "// GENERATED by `node mcp-app/build.mjs` — do not edit. The proposal card (MCP Apps), one",
    "// inline HTML document; `app/mcp/apps/__tests__/proposalCard.test.tsx` fails when it is stale.",
    "",
    `export const PROPOSAL_CARD_HTML = ${JSON.stringify(html)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const html = await buildProposalCardHtml();
  writeFileSync(GENERATED_FILE, generatedModule(html));
  console.log(`proposal card: ${html.length} characters → ${path.relative(process.cwd(), GENERATED_FILE)}`);
}
